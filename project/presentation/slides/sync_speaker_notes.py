#!/usr/bin/env python3
"""Refresh Beamer notes from the outline without changing slide content."""
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
OUTLINE = HERE.parent / "presentation_outline.md"
WORDS = ("One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight")
SOURCES = (
    "Client brief; design notebook, Helion context; benchmark report.",
    "Pipeline README; MOCK-ENG-002; benchmark report, section 2.",
    "validation.json; SYN-OPS-001; benchmark evidence boundary.",
    "predictive_metrics.csv; predictive_paired_comparisons.csv; training.json; calibration figure.",
    "decision_metrics.csv (base/test); decision_uncertainty.csv; verification.json; benchmark report.",
    "scheduling.json; walkthroughs.json; SYN-OPS-001 Case D.",
    "Design notebook, operations; helion-architecture.mmd; pipeline README; run_manifest.json.",
    "Benchmark limitations and next evidence; client brief; SYN-OPS-001 section 6.",
)
ESCAPES = {
    "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$",
    "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
    "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
    "–": "--", "—": "---", "−": r"$-$", "×": r"$\times$",
    "’": "'", "“": "``", "”": "''",
}


def tex(text: str) -> str:
    return "".join(ESCAPES.get(char, char) for char in text)


def main() -> None:
    source = OUTLINE.read_text()
    blocks = re.split(r"(?m)^## Slide \d+: ", source)[1:]
    if len(blocks) != 8:
        raise ValueError("Expected exactly eight slide sections in the outline")
    lines = ["% Generated by sync_speaker_notes.py from the presentation outline.",
             "% Edit the outline then rerun the script to refresh these notes."]
    for word, block, sources in zip(WORDS, blocks, SOURCES):
        title = block.splitlines()[0]
        timing = re.search(r"\*\*Time:\*\* ([\d:]+)–([\d:]+)", block)
        notes = re.search(r"\*\*Speaker notes\*\*\n\n(.*?)(?=\n\n\*\*(?:Evidence|Visual option))", block, re.S)
        if timing is None or notes is None:
            raise ValueError(f"Missing notes or timing for {title}")
        lines += [
            rf"\newcommand{{\Slide{word}Notes}}{{%",
            r"\textbf{" + tex(title) + r"}\par\smallskip",
            r"\textbf{Time: " + tex(f"{timing[1]}–{timing[2]}") + r"}\par\medskip",
            tex(notes[1].strip()) + r"\par\medskip",
            r"{\fontsize{7}{8.5}\selectfont\color{Muted}Evidence: " + tex(sources) + r"\par}",
            "}",
        ]
    (HERE / "speaker_notes.tex").write_text("\n".join(lines) + "\n")
    print("Updated eight timed speaker notes from the presentation outline.")


if __name__ == "__main__":
    main()
